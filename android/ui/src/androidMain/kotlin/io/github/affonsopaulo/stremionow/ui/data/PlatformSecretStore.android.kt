package io.github.affonsopaulo.stremionow.ui.data

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import io.github.affonsopaulo.stremionow.ui.platform.PlatformContext
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Secrets encrypted with an AES key that lives in the Android Keystore and never leaves it.
 * The encrypted values sit in private preferences, which the app's backup rules already exclude.
 */
internal actual object PlatformSecretStore {
    private const val KEYSTORE = "AndroidKeyStore"
    private const val KEY_ALIAS = "stremionow.secrets"
    private const val PREFERENCES = "secrets"
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val TAG_BITS = 128

    /** GCM uses a 12-byte IV, generated by the Keystore for each encryption. */
    private const val GCM_IV_BYTES = 12

    actual fun save(
        context: PlatformContext,
        name: String,
        value: String,
    ) {
        val cipher = Cipher.getInstance(TRANSFORMATION).apply { init(Cipher.ENCRYPT_MODE, key()) }
        val sealed = cipher.iv + cipher.doFinal(value.toByteArray(Charsets.UTF_8))
        preferences(context).edit().putString(name, Base64.encodeToString(sealed, Base64.NO_WRAP)).apply()
    }

    actual fun load(
        context: PlatformContext,
        name: String,
    ): String? {
        val encoded = preferences(context).getString(name, null) ?: return null
        return runCatching {
            val sealed = Base64.decode(encoded, Base64.NO_WRAP)
            val iv = sealed.copyOfRange(0, GCM_IV_BYTES)
            val cipher =
                Cipher.getInstance(TRANSFORMATION).apply {
                    init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, iv))
                }
            String(cipher.doFinal(sealed, GCM_IV_BYTES, sealed.size - GCM_IV_BYTES), Charsets.UTF_8)
        }.getOrElse {
            // A reset Keystore (for example after a device restore) makes old values unreadable.
            clear(context, name)
            null
        }
    }

    actual fun clear(
        context: PlatformContext,
        name: String,
    ) {
        preferences(context).edit().remove(name).apply()
    }

    private fun preferences(context: Context) =
        context.applicationContext.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)

    /** Synchronized so two first uses cannot create two keys and lose a value to the other. */
    @Synchronized
    private fun key(): SecretKey {
        val keyStore = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        (keyStore.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }
        return KeyGenerator
            .getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
            .apply {
                init(
                    KeyGenParameterSpec
                        .Builder(KEY_ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                        .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                        .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                        .setKeySize(256)
                        .build(),
                )
            }.generateKey()
    }
}
